"""Build api/migrations/seed_demo_004.sql from scripts/seed/harbor_inventory.yaml and the
policy templates in content/policies. Run from the repo root:

    python3 scripts/seed/build_seed_004.py > api/migrations/seed_demo_004.sql

A test rebuilds it and fails if the committed file is out of date.
"""
import json
import sys
import uuid
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "api"))

from opendpo import policies  # noqa: E402

NS = uuid.UUID("5f2b7c1e-0d4a-4b8e-9a51-0b0e0d0f0001")
TENANT = uuid.uuid5(NS, "tenant:harbor")


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"harbor:{kind}:{key}"))


def user(username: str) -> str:
    return str(uuid.uuid5(NS, f"user:{username}"))


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False, sort_keys=True).replace("'", "''") + "'::jsonb"
    return "'" + " ".join(str(v).split()).replace("'", "''") + "'"


def insert(table: str, row: dict) -> str:
    cols = ", ".join(row)
    vals = ", ".join(q(v) for v in row.values())
    return f"INSERT INTO {table} ({cols}) VALUES ({vals});"


def build(inv: dict, templates: list[policies.Template]) -> str:
    t = str(TENANT)
    out = ["-- Demo seed, part 4: Harbor Staffing's inventory and its copy of two policies.",
           "-- Fictional. Generated by scripts/seed/build_seed_004.py; do not edit by hand.", ""]
    for username, title in inv["job_titles"].items():
        out.append(f"UPDATE app_user SET job_title = {q(title)} WHERE username = {q(username)};")
    out.append("")
    for v in inv["vendors"]:
        out.append(insert("vendor", {"id": uid("vendor", v["key"]), "tenant_id": t, "name": v["name"],
                                     "role": v["role"], "dpa_status": v["dpa_status"],
                                     "locations": v["locations"], "notes": v.get("notes")}))
    for s in inv["systems"]:
        out.append(insert("system", {"id": uid("system", s["key"]), "tenant_id": t, "name": s["name"],
                                     "business_owner": s["business_owner"], "technical_owner": s.get("technical_owner"),
                                     "origin": s["origin"], "vendor_id": uid("vendor", s["vendor"]) if s.get("vendor") else None,
                                     "hosting": s.get("hosting"), "locations": s["locations"],
                                     "sensitivity": s["sensitivity"], "status": s["status"]}))
    for a in inv["ai_components"]:
        out.append(insert("ai_component", {
            "id": uid("ai", a["key"]), "tenant_id": t, "name": a["name"], "origin": a["origin"], "kind": a["kind"],
            "vendor_id": uid("vendor", a["vendor"]) if a.get("vendor") else None, "version": a.get("version"),
            "intended_use": a["intended_use"], "inputs": a["inputs"], "output": a["output"],
            "trained_on_personal_data": a["trained_on_personal_data"], "known_limitations": a.get("known_limitations")}))
        for s in a.get("systems", []):
            out.append(insert("system_ai_component", {"tenant_id": t, "system_id": uid("system", s),
                                                      "ai_component_id": uid("ai", a["key"])}))
    for d in inv["data_categories"]:
        out.append(insert("data_category", {"id": uid("data", d["key"]), "tenant_id": t, "name": d["name"],
                                            "examples": d.get("examples"), "sensitive": d["sensitive"],
                                            "ccpa_category": d.get("ccpa_category"), "retention": d["retention"]}))
    for g in inv["subject_groups"]:
        out.append(insert("data_subject_group", {"id": uid("group", g["key"]), "tenant_id": t, "name": g["name"],
                                                 "approximate_count": g.get("approximate_count"),
                                                 "jurisdictions": g["jurisdictions"]}))
    for act in inv["activities"]:
        aid = uid("activity", act["key"])
        out.append(insert("processing_activity", {
            "id": aid, "tenant_id": t, "name": act["name"], "purpose": act["purpose"],
            "legal_basis": act.get("legal_basis"), "decision_domain": act.get("decision_domain"),
            "ai_role": act.get("ai_role"), "human_review": act.get("human_review"),
            "human_review_note": act.get("human_review_note"), "people_affected": act.get("people_affected", {}),
            "collection": act.get("collection"), "consumer_interaction": act.get("consumer_interaction"),
            "disclosures": act.get("disclosures"), "go_live": str(act["go_live"]) if act.get("go_live") else None,
            "stage": act.get("stage")}))
        for s in act["systems"]:
            out.append(insert("activity_system", {"tenant_id": t, "activity_id": aid, "system_id": uid("system", s)}))
        for a in act["ai_components"]:
            out.append(insert("activity_ai_component", {"tenant_id": t, "activity_id": aid,
                                                        "ai_component_id": uid("ai", a)}))
        for d, why in act["data_categories"].items():
            out.append(insert("activity_data_category", {"tenant_id": t, "activity_id": aid,
                                                         "data_category_id": uid("data", d), "why_needed": why}))
        for g in act["subject_groups"]:
            out.append(insert("activity_subject_group", {"tenant_id": t, "activity_id": aid,
                                                         "group_id": uid("group", g)}))
        for v, why in act["recipients"].items():
            out.append(insert("activity_recipient", {"tenant_id": t, "activity_id": aid,
                                                     "vendor_id": uid("vendor", v), "purpose": why}))
    out.append("")
    appr = inv["policy_approvals"]
    for tpl in templates:
        pid, vid = uid("policy", tpl.id), uid("policy-version", f"{tpl.id}:1")
        sections = [{"number": s.number, "title": s.title,
                     "text": s.text.replace("{organization}", "Harbor Staffing").strip()} for s in tpl.sections]
        out.append(insert("policy", {"id": pid, "tenant_id": t, "template_id": tpl.id, "title": tpl.title}))
        out.append(insert("policy_version", {
            "id": vid, "tenant_id": t, "policy_id": pid, "version": 1, "template_version": tpl.version,
            "sections": sections, "status": "confirmed", "proposed_by": user(appr["proposed_by"]),
            "confirmed_by": user(appr["confirmed_by"]), "confirmed_at": appr["confirmed_at"],
            "effective_from": str(appr["effective_from"])}))
        for p in tpl.positions:
            out.append(insert("policy_position", {
                "id": uid("position", f"{tpl.id}:1:{p.id}"), "tenant_id": t, "policy_version_id": vid,
                "position_key": p.id, "section": p.section, "type": p.type, "statement": p.statement,
                "applies_to": p.applies_to, "parameters": p.parameters, "framework_refs": p.framework_refs}))
    return "\n".join(out) + "\n"


def main() -> str:
    inv = yaml.safe_load((ROOT / "scripts" / "seed" / "harbor_inventory.yaml").read_text(encoding="utf-8"))
    return build(inv, [s.template for s in policies.load()])


if __name__ == "__main__":
    sys.stdout.write(main())
